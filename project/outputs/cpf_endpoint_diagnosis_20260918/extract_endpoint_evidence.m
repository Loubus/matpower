function evidence=extract_endpoint_evidence
% Extract measured accepted points and rejected transition diagnostics.
out=fileparts(mfilename('fullpath'));
src=load(fullfile(out,'../cpf_branch_preserving_release_20260918/verified/full_050_release1.mat'));
run=load(fullfile(out,'instrumented_run.mat')); r=src.result; c=idx_vsc;
assert(isequaln(run.probe_result.cpf.lam,r.cpf.lam));
assert(isequaln(run.probe_result.cpf.vsc,r.cpf.vsc));
tr=run.CPF_STOP_TRACE; n=numel(r.cpf.lam);
current=zeros(n,3);internal=current;p=current;q=current;v=current;
for k=1:n
 for j=1:3
  row=r.cpf.vsc(j,:,k);
  [~,~,~,~,info]=vsc_capability_curve(row(c.PAC),row(c.QAC),150, ...
      row(c.VAC_PCC),row,[],1.15,r.baseMVA);
  current(k,j)=info.converter_current_pu;
  internal(k,j)=row(c.VAC_INTERNAL);
  p(k,j)=row(c.PAC);q(k,j)=row(c.QAC);v(k,j)=row(c.VAC_PCC);
 end
end
enter=find(cellfun(@(a)strcmp(a.tag,'stage_enter'),tr),1,'last');
cascade=struct('lambda',{},'V5',{},'P3',{},'Q3',{},'I3_ratio',{}, ...
    'next_P3',{},'next_Q3',{},'event_method',{});
transitions=struct('lambda',{},'residual',{},'success',{},'state_gap',{},'iterations',{});
for k=enter:numel(tr)
 a=tr{k};
 if strcmp(a.tag,'capability_update')
  row=a.r.vsc(3,:);
  [~,~,~,~,info]=vsc_capability_curve(row(c.PAC),row(c.QAC),150, ...
      row(c.VAC_PCC),row,[],1.15,r.baseMVA);
  cascade(end+1)=struct('lambda',a.lambda,'V5',row(c.VAC_PCC), ...
      'P3',row(c.PAC),'Q3',row(c.QAC),'I3_ratio',info.converter_current_pu, ...
      'next_P3',a.report.P_saturated,'next_Q3',a.report.Q_saturated, ...
      'event_method',a.report.event_location_method{1}); %#ok<AGROW>
 elseif strcmp(a.tag,'transition_exit')
  transitions(end+1)=struct('lambda',a.lambda,'residual',a.residual, ...
      'success',a.success,'state_gap',a.state_gap,'iterations',a.iterations); %#ok<AGROW>
 end
end
attempts=struct('k',{},'step',{},'candidate_lambda',{},'candidate_residual',{}, ...
    'post_transition_lambda',{},'stage_success',{});
for k=1:numel(tr)
 if strcmp(tr{k}.tag,'stage_enter')
  a=tr{k}; ee=k+find(cellfun(@(b)strcmp(b.tag,'stage_exit'),tr(k+1:end)),1);
  b=tr{ee};
  attempts(end+1)=struct('k',a.k,'step',a.step,'candidate_lambda',a.lambda, ...
      'candidate_residual',a.residual,'post_transition_lambda',b.lambda, ...
      'stage_success',b.success); %#ok<AGROW>
 end
end
last=struct('lambda',r.cpf.lam(end),'total_demand_MW',sum(r.bus(:,3)), ...
    'V5',v(end,3),'current_ratios',current(end,:), ...
    'internal_voltages',internal(end,:),'P',p(end,:),'Q',q(end,:), ...
    'equation_mismatch',r.convergence.max_mismatch, ...
    'tap',r.branch(9,9),'shunt_B_MVAr_at_1pu',r.bus(5,6), ...
    'actual_shunt_MVAr',r.bus(5,6)*r.bus(5,8)^2, ...
    'G2_P_MW',r.gen(2,2),'G2_Q_MVAr',r.gen(2,3));
evidence=struct('source','../cpf_branch_preserving_release_20260918/verified/full_050_release1.mat', ...
    'instrumented_replay_matches',true,'warning',run.probe_warning, ...
    'last',last,'termination',r.cpf.termination,'saved_failure',r.cpf.failure, ...
    'lambda',r.cpf.lam(:),'demand_MW',reshape(sum(r.cpf.bus(:,3,:),1),[],1), ...
    'VSC_P_MW',p,'VSC_Q_MVAr',q,'VSC_PCC_pu',v,'VSC_internal_pu',internal, ...
    'VSC_current_ratio',current,'corrector_iterations',r.cpf.corrector_iterations(:), ...
    'steps',r.cpf.steps(:),'last_attempt_cascade',cascade, ...
    'last_attempt_transitions',transitions,'attempts',attempts, ...
    'current_contact_voltage_for_fixed_PQ',hypot(35,5)/150, ...
    'step_min',src.o.cpf.step_min,'last_trial_step',tr{enter}.step, ...
    'candidate_residual_before_capability',tr{enter}.residual);
fid=fopen(fullfile(out,'evidence.json'),'w');guard=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(evidence,PrettyPrint=true));
disp(last); disp(struct2table(cascade));disp(struct2table(transitions));
end
