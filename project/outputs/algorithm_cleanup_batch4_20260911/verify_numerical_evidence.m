function verify_numerical_evidence(outdir)
% Compare accepted pre/post extraction results without comparing run timings.
before=load(fullfile(outdir,'beerten_preextraction_02','evidence','beerten.mat'));
after=load(fullfile(outdir,'beerten_final','evidence','beerten.mat'));
summary=struct(); equal=struct();
for label={'shunt_only','combined'}
    name=label{1}; a=before.evidence.(name); b=after.evidence.(name);
    equal.(name)=struct('lambda',isequaln(a.cpf.cpf.lam,b.cpf.cpf.lam), ...
        'stored_state',isequaln(a.cpf.cpf.x,b.cpf.cpf.x), ...
        'bus',isequaln(a.cpf.cpf.bus,b.cpf.cpf.bus), ...
        'branch',isequaln(a.cpf.cpf.branch,b.cpf.cpf.branch), ...
        'vsc',isequaln(a.cpf.cpf.vsc,b.cpf.cpf.vsc), ...
        'events',isequaln(a.cpf.cpf.events,b.cpf.cpf.events), ...
        'half_state',isequaln(a.half_step.cpf.x,b.half_step.cpf.x));
    assert(all(structfun(@(v) v,equal.(name))),'Extraction changed accepted Beerten results');
    summary.(name)=struct('success',b.cpf.success,'lambda',b.cpf.cpf.lam(end), ...
        'points',length(b.cpf.cpf.lam),'target_tolerance',b.options.cpf.target_lam_tol, ...
        'shunt_trace',squeeze(b.cpf.cpf.bus(5,6,:)), ...
        'tap_trace',squeeze(b.cpf.cpf.branch(9,9,:)), ...
        'events',{b.cpf.cpf.events},'automatic_pf_success',b.automatic_pf.success, ...
        'half_success',b.half_step.success,'half_lambda',b.half_step.cpf.lam(end), ...
        'half_voltage_difference',max(abs(b.half_step.ac.bus(:,8)-b.cpf.ac.bus(:,8))), ...
        'automatic_voltage_difference',max(abs(b.automatic_pf.ac.bus(:,8)-b.cpf.ac.bus(:,8))));
end
ab=load(fullfile(outdir,'acceptance_preextraction','evidence','shunt.mat'));
aa=load(fullfile(outdir,'acceptance_final','evidence','shunt.mat'));
equal.acceptance_checks=isequaln(ab.checks,aa.checks);
assert(equal.acceptance_checks,'Extraction changed acceptance observations');
for name={'lock1','lock2','lock3','screening','continuous'}
    equal.(name{1})=isequaln(ab.evidence.(name{1}),aa.evidence.(name{1}));
    assert(equal.(name{1}),'Extraction changed saved shunt decision');
end
probe=load(fullfile(outdir,'beerten_probe.mat'));
summary.long_probe=struct('success',probe.b4r.success,'last_lambda',probe.b4r.cpf.lam(end), ...
    'done_msg',probe.b4r.cpf.done_msg,'electrical_convergence',probe.b4r.convergence, ...
    'events',{probe.b4r.cpf.events});
writejson('numerical_summary.json',summary);
writejson('prepost_equivalence.json',equal);
    function writejson(filename,value)
        fid=fopen(fullfile(outdir,filename),'w'); cleanup=onCleanup(@() fclose(fid));
        fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
    end
end
