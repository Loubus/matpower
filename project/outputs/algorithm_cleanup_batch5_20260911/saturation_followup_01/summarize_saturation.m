function summary=summarize_saturation(folder)
out=fileparts(mfilename('fullpath'));
s=load(fullfile(folder,'saturation.mat'));
r=s.evidence.cpf;
summary=struct('termination',r.cpf.termination, ...
    'convergence',r.convergence,'lambda',r.cpf.lam, ...
    'vm5',r.bus(r.bus(:,1)==5,8),'tap',r.branch(9,9), ...
    'B',r.psse.swshunt.control.final_binit, ...
    'events',r.cpf.events,'capability',s.evidence.endpoint_capability_audit, ...
    'original_options',s.evidence.original_options,'options',s.evidence.options);
for k=1:numel(s.evidence.automatic)
    p=s.evidence.automatic{k};
    summary.automatic(k)=struct('success',p.success,'vm5',p.ac.bus(p.ac.bus(:,1)==5,8), ...
        'acceptance',p.convergence.psse_controls.acceptance, ...
        'residual',p.convergence.max_mismatch);
end
fid=fopen(fullfile(out,'summary.json'),'w');fprintf(fid,'%s\n',jsonencode(summary,'PrettyPrint',true));fclose(fid);
end
