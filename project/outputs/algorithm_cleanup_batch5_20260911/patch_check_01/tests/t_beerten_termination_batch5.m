function [checks,evidence] = t_beerten_termination_batch5(quiet,outdir)
%T_BEERTEN_TERMINATION_BATCH5 Reproduce and classify the saved control bound.
% Fixed-state diagnostics are separate from the automatic-control trace.
if nargin < 1, quiet=0; end
root=fileparts(fileparts(mfilename('fullpath')));
if nargin < 2, outdir=tempname(fullfile(root,'outputs')); end
assert(~isfolder(outdir),'Use a fresh output directory'); mkdir(outdir);
s=load(fullfile(root,'outputs','algorithm_cleanup_batch4_20260911','beerten_probe.mat'));
f=s.b4f; target=s.b4t; opt=s.b4o; c=idx_vsc;
checks=struct('id',{},'passed',{},'detail',{});
[r,success]=runcpf_psse(f,target,opt);
d=r.cpf.failure.diagnostic; candidate=d.candidate;
sh=mp.psse_swshunt_states(f); xf=mp.psse_xfmr_states(f);
evidence=struct('base',f,'target',target,'options',opt,'result',r,'fixed',{{}},'steps',{{}});
check('outcome',~success && ~r.success && ~r.cpf.termination.success, ...
    'automatic target remains unsuccessful under unchanged options');
check('trace_preserved',isequaln(r.cpf.x,s.b4r.cpf.x) && ...
    isequaln(r.cpf.lam,s.b4r.cpf.lam) && isequaln(r.cpf.bus,s.b4r.cpf.bus) && ...
    isequaln(r.cpf.branch,s.b4r.cpf.branch) && isequaln(r.cpf.gen,s.b4r.cpf.gen) && ...
    isequaln(r.cpf.vsc,s.b4r.cpf.vsc), 'exact historical accepted electrical trace');
check('bound',strcmp(r.cpf.termination.cause,'control_bound') && ...
    d.decisions{end}.report.swshunt_blocked_low==1 && ...
    d.decisions{end}.report.xfmr_blocked_violations==0, 'shunt bound, not a tap rejection');
check('no_correction',~d.correction_attempted && d.correction_iterations==0 && ...
    isempty(d.correction_residual) && ~d.decisions{end}.changed, ...
    'no discrete change or electrical re-correction at rejected point');
check('candidate_solved',d.candidate_electrical_converged && candidate.success && ...
    candidate.convergence.max_mismatch<candidate.convergence.tol, ...
    'rejected control candidate has a converged full electrical solve');
check('scoped_convergence',r.convergence.converged && ...
    ~r.convergence.overall_success && strcmp(r.convergence.scope,'last_accepted_point') && ...
    r.convergence.lambda==r.cpf.lam(end), 'electrical convergence applies only to exported accepted point');
check('last_accepted',r.cpf.termination.last_accepted_lambda==r.cpf.lam(end) && ...
    r.cpf.termination.last_accepted_index==numel(r.cpf.lam) && ...
    r.cpf.failure.lambda>r.cpf.lam(end) && isequal(r.bus,r.cpf.bus(:,:,end)), ...
    'candidate is excluded from accepted trace and result arrays');
check('no_nose',~r.cpf.termination.nose_detected && ...
    ~r.cpf.termination.stability_margin_validated && ...
    ~r.cpf.termination.requested_endpoint_reached && ...
    strcmp(r.cpf.termination.max_lam_scope,'accepted_trace_maximum'), ...
    'failed endpoint is neither requested target nor a validated stability margin');
check('message',contains(r.cpf.done_msg,'control_bound') && ...
    ~contains(r.cpf.done_msg,'re-correction'), 'message names actual rejection');
check('no_recovery',~any(contains({r.cpf.events.name},'FREEZE')) && ...
    strcmp(r.cpf.active_set_failure_policy.psse_control.declared_policy,'stop'), ...
    'no new freeze or lockout policy');
check('threshold',r.bus(5,8)>=sh.vswlo-sh.vtol && ...
    candidate.bus(5,8)<sh.vswlo-sh.vtol && candidate.bus(5,6)==sh.bmax, ...
    'last accepted and rejected points bracket unchanged voltage tolerance at maximum B');
check('tap_in_band',candidate.bus(xf.reg_bus_idx,8)>=xf.vmi-xf.vtol && ...
    candidate.bus(xf.reg_bus_idx,8)<=xf.vma+xf.vtol && ...
    isequal(candidate.branch(:,9),r.branch(:,9)), 'ULTC regulated bus remains in band');
check('active_set',isequal(candidate.bus(:,2),r.bus(:,2)) && ...
    isequal(candidate.gen(:,[4 5 6 8]),r.gen(:,[4 5 6 8])) && ...
    isequal(candidate.vsc(:,[3 4 5]),r.vsc(:,[3 4 5])), ...
    'no generator, bus or converter mode switch at rejected candidate');
audit=check_capability_limits(candidate); evidence.capability_audit=audit;
check('capability',audit.violations==0 && all(candidate.gen(:,3)<=f.gen(:,4)+.01) && ...
    all(candidate.gen(:,3)>=f.gen(:,5)-.01), 'original generator and converter capability audit passes');
physical('accepted',r); physical('candidate',candidate);
% Every accepted point remains independently solvable on its explicit state.
for k=1:numel(r.cpf.lam)
    p=f; lam=r.cpf.lam(k);
    p.bus(:,[3 4])=f.bus(:,[3 4])+lam*(target.bus(:,[3 4])-f.bus(:,[3 4]));
    p.bus(:,6)=r.cpf.bus(:,6,k); p.branch(:,1:13)=r.cpf.branch(:,1:13,k);
    pf=runpf_vsc_mtdc(p,opt);
    [~,rows]=ismember(r.cpf.bus(:,1,k),pf.ac.bus(:,1));
    check(sprintf('point%d.fixed',k),pf.success && ...
        max(abs(pf.ac.bus(rows,8)-r.cpf.bus(:,8,k)))<1e-6, 'independent full PF matches accepted state');
end
% Around the event, enumerate all original B states at the accepted tap.
for lam=[r.cpf.lam(end) r.cpf.failure.lambda .42 .45]
    for B=sh.states{1}'
        p=f;
        p.bus(:,[3 4])=f.bus(:,[3 4])+lam*(target.bus(:,[3 4])-f.bus(:,[3 4]));
        p.branch(:,1:13)=r.branch(:,1:13);
        p.bus(5,6)=sh.base_bs(5)+B; p.psse.swshunt.num(:,sh.binit_col)=B;
        pf=runpf_vsc_mtdc(p,opt); % explicit fixed state, original PF options
        tag=sprintf('fixed%.8f.B%g',lam,B); physical(tag,pf);
        vm=pf.ac.bus(pf.ac.bus(:,1)==5,8);
        check([tag '.solved'],pf.success,'full PF converges with original equations and limits');
        if lam>=r.cpf.failure.lambda
            check([tag '.outside_band'],vm<sh.vswlo-sh.vtol,'all legal B states remain below the band');
        end
        if lam==r.cpf.failure.lambda && B==sh.bmax
            [~,rows]=ismember(candidate.bus(:,1),pf.ac.bus(:,1));
            check('candidate_pf_match',max(abs(pf.ac.bus(rows,8)-candidate.bus(:,8)))<1e-6, ...
                'independent full PF reproduces rejected candidate voltage');
        end
        evidence.fixed{end+1}=struct('lambda',lam,'B',B,'input',p,'result',pf);
    end
end
for step=[.05 .025]
    op=mpoption(opt,'cpf.step',step); a=runcpf_psse(f,target,op);
    check(sprintf('step%g',step),~a.success && strcmp(a.cpf.termination.cause,'control_bound') && ...
        a.cpf.failure.diagnostic.candidate_electrical_converged && ...
        abs(a.cpf.lam(end)-r.cpf.lam(end))<2e-4 && ...
        a.bus(5,8)>=sh.vswlo-sh.vtol && ...
        a.cpf.failure.diagnostic.candidate.bus(5,8)<sh.vswlo-sh.vtol, ...
        'same control boundary bracket with finer continuation step');
    evidence.steps{end+1}=struct('options',op,'result',a);
end
short=runcpf_psse(f,target,mpoption(opt,'cpf.stop_at',.4));
check('requested_success',short.success && short.convergence.overall_success && ...
    short.cpf.termination.requested_endpoint_reached && ...
    strcmp(short.cpf.termination.cause,'requested_lambda'), 'short requested endpoint is explicitly reached');
nose=runcpf_psse(f,target,mpoption(opt,'cpf.stop_at','NOSE'));
check('nose_request_bound',nose.success && strcmp(nose.cpf.termination.cause,'control_bound') && ...
    ~nose.cpf.termination.requested_endpoint_reached && ~nose.cpf.termination.nose_detected && ...
    strcmp(nose.cpf.termination.success_scope,'configured_stop_policy'), ...
    'legacy successful bound stop is explicit and is not a detected nose');
evidence.short=short; evidence.nose_request=nose;
save(fullfile(outdir,'termination.mat'),'checks','evidence','-v7.3');
fid=fopen(fullfile(outdir,'checks.json'),'w'); fprintf(fid,'%s\n',jsonencode(checks,'PrettyPrint',true)); fclose(fid);
t_begin(numel(checks),quiet);
for k=1:numel(checks), t_ok(checks(k).passed,[checks(k).id ': ' checks(k).detail]); end
t_end;
    function check(id,passed,detail)
        checks(end+1)=struct('id',id,'passed',logical(passed),'detail',detail);
    end
    function physical(tag,p)
        a=ext2int(p.ac); v=a.bus(:,8).*exp(1j*pi/180*a.bus(:,9));
        ac=norm(v.*conj(makeYbus(a.baseMVA,a.bus,a.branch)*v)-makeSbus(a.baseMVA,a.bus,a.gen),Inf);
        [~,rows]=ismember(p.vsc(:,c.BUSDC),p.busdc(:,1));
        injection=accumarray(rows,p.vsc(:,c.PDC),[size(p.busdc,1) 1])/f.baseMVA;
        dc=norm(p.busdc(:,3).*(makeGdc(p.busdc,p.branchdc)*p.busdc(:,3))-injection,Inf);
        conv=max(abs(sum(p.vsc(:,[c.PAC c.PDC c.PLOSS]),2)))/f.baseMVA;
        check([tag '.balance'],ac<1e-8 && dc<1e-8 && conv<1e-8, ...
            sprintf('full AC %.3g DC %.3g converter %.3g pu',ac,dc,conv));
    end
end
