function t_vsc_mtdc(quiet)
% t_vsc_mtdc - Tests for AC/DC VSC-MTDC power flow.

%   MATPOWER
%   Copyright (c) 2026, Power Systems Engineering Research Center (PSERC)
%
%   This file is part of MATPOWER.
%   Covered by the 3-clause BSD License (see LICENSE file for details).
%   See https://matpower.org for more info.

if nargin < 1
    quiet = 0;
end

num_tests = 271;

t_begin(num_tests, quiet);

%% define named indices into data matrices
[PQ, ~, REF, ~, BUS_I, BUS_TYPE, PD, QD, ~, BS, ~, VM, VA] = idx_bus;
[F_BUS, T_BUS, BR_R, BR_X, ~, ~, ~, ~, TAP, ~, BR_STATUS, PF, QF, ~, QT] = idx_brch;
[GEN_BUS, PG, QG, QMAX, ~, ~, ~, GEN_STATUS] = idx_gen;
c = idx_vsc;
bdc = idx_busdc;
brdc = idx_branchdc;

mpopt = mpoption('out.all', 0, 'verbose', 0);
mpopt_seq = mpopt;
mpopt_seq.vsc_mtdc.method = 'sequential';
mpopt_u = mpopt;
mpopt_u.vsc_mtdc.method = 'unified';

%%-----  2-terminal VSC-MTDC case  -----
mpc2 = loadcase('case3_vsc_mtdc_2term');
active2 = find(mpc2.vsc(:, c.VSC_STATUS) > 0);
Gdc = makeGdc(mpc2.busdc, mpc2.branchdc);
t_is(full(Gdc), [100 -100; -100 100], 12, 'makeGdc ignores out-of-service DC branch');

[r2, success] = runpf_vsc_mtdc(mpc2, mpopt_seq);
t_ok(success, '2-terminal VSC-MTDC PF success');
t_ok(r2.iterations > 0 && r2.iterations <= 20, '2-terminal iteration count');
t_is(r2.vsc(active2, c.PAC) + r2.vsc(active2, c.PDC) + r2.vsc(active2, c.PLOSS), ...
    zeros(length(active2), 1), 6, '2-terminal VSC power balance');
t_is(r2.busdc(:, bdc.VDC), [1; 1.0049752469181], 8, '2-terminal DC voltages');
slack2 = find(r2.vsc(:, c.IS_DC_SLACK) > 0);
t_is(slack2, 1, 12, '2-terminal DC slack identification');
t_ok(abs(r2.vsc(slack2, c.PDC) - mpc2.vsc(slack2, c.PDC_SET)) > 1, ...
    '2-terminal slack Pdc is calculated result');
t_is(r2.branchdc(2, brdc.PFDC:brdc.ITDC), zeros(1, 4), 12, ...
    'out-of-service DC branch ignored');
t_is(r2.vsc(3, [c.PAC c.QAC c.PDC c.PLOSS c.FILTER_BUS c.INTERNAL_BUS]), ...
    zeros(1, 6), 12, 'out-of-service VSC ignored');
t_ok(all(r2.vsc(active2, c.PLOSS) > 0), '2-terminal VSC losses are positive');

t_is(size(r2.ac.bus, 1), size(mpc2.bus, 1) + 2 * length(active2), 12, ...
    '2-terminal auxiliary AC buses');
t_is(size(r2.ac.branch, 1), size(mpc2.branch, 1) + 2 * length(active2), 12, ...
    '2-terminal transformer and reactor branches');
t_is(r2.vsc(active2, c.FILTER_BUS), [4; 6], 12, '2-terminal filter bus numbering');
t_is(r2.vsc(active2, c.INTERNAL_BUS), [5; 7], 12, '2-terminal internal bus numbering');
t_is(r2.ac.branch(r2.vsc(1, c.TR_BRANCH), BR_R:BR_X), ...
    mpc2.vsc(1, c.TR_R:c.TR_X), 12, 'transformer branch keeps own impedance');
t_is(r2.ac.branch(r2.vsc(1, c.TR_BRANCH), TAP), 0, 12, ...
    'converter station transformer has no tap');
t_is(r2.ac.branch(r2.vsc(1, c.REACTOR_BRANCH), BR_R:BR_X), ...
    mpc2.vsc(1, c.REACTOR_R:c.REACTOR_X), 12, 'reactor branch keeps own impedance');
frow = find(r2.ac.bus(:, BUS_I) == r2.vsc(1, c.FILTER_BUS), 1);
t_is(r2.ac.bus(frow, BS), mpc2.vsc(1, c.FILTER_B) * mpc2.baseMVA, 12, ...
    'filter shunt is on filter bus');
equiv = find(r2.ac.branch(:, F_BUS) == mpc2.vsc(1, c.VSC_BUS) & ...
             r2.ac.branch(:, T_BUS) == r2.vsc(1, c.INTERNAL_BUS) & ...
             r2.ac.branch(:, BR_STATUS) > 0, 1);
t_ok(isempty(equiv), 'no transformer plus reactor equivalent branch');

%%-----  VSC-MTDC savecase round-trip  -----%%
mpc2_save = mpc2;
mpc2_save.vsc_capability = struct('Snom', [70 80 90], ...
    'VconvMax', [1.15 1.15 1.15]);
mpc2_save.vsc_hvdc_dispatch = struct('policy', 'constant', ...
    'delta_pd', 0, ...
    'delta_pdc_set', zeros(size(mpc2.vsc, 1), 1));
fn_vsc = sprintf('vsc_mtdc_savecase_test_%d', fix(1e8*rand));
savecase(fn_vsc, mpc2_save);
txt_vsc = fileread([fn_vsc '.m']);
mpc2_rt = loadcase(fn_vsc);
delete([fn_vsc '.m']);
t_ok(~isempty(strfind(txt_vsc, 'mpc.busdc = [')) && ...
    ~isempty(strfind(txt_vsc, 'mpc.branchdc = [')) && ...
    ~isempty(strfind(txt_vsc, 'mpc.vsc = [')), ...
    'savecase writes VSC-MTDC matrices');
t_is(mpc2_rt.busdc, mpc2.busdc, 12, ...
    'savecase/loadcase preserves busdc');
t_is(mpc2_rt.branchdc, mpc2.branchdc, 12, ...
    'savecase/loadcase preserves branchdc');
t_is(mpc2_rt.vsc, mpc2.vsc, 12, ...
    'savecase/loadcase preserves vsc');
t_is(mpc2_rt.vsc_capability.Snom, mpc2_save.vsc_capability.Snom, 12, ...
    'savecase/loadcase preserves VSC capability metadata');
t_str_match(mpc2_rt.vsc_hvdc_dispatch.policy, 'constant', ...
    'savecase/loadcase preserves VSC/HVDC dispatch policy');
t_is(mpc2_rt.vsc_hvdc_dispatch.delta_pdc_set, ...
    mpc2_save.vsc_hvdc_dispatch.delta_pdc_set, 12, ...
    'savecase/loadcase preserves VSC/HVDC dispatch vectors');
[~, success] = runpf_vsc_mtdc(mpc2_rt, mpopt_u);
t_ok(success, 'savecase/loadcase VSC-MTDC case can be re-solved');

fn_pf = sprintf('vsc_mtdc_pf_solvedcase_test_%d', fix(1e8*rand));
[~, success] = runpf_vsc_mtdc(mpc2, mpopt_u, '', fn_pf);
mpc2_pf_rt = loadcase(fn_pf);
delete([fn_pf '.m']);
t_ok(success && isfield(mpc2_pf_rt, 'busdc') && ...
    isfield(mpc2_pf_rt, 'branchdc') && isfield(mpc2_pf_rt, 'vsc'), ...
    'runpf_vsc_mtdc solvedcase preserves VSC-MTDC fields');
[~, success] = runpf_vsc_mtdc(mpc2_pf_rt, mpopt_u);
t_ok(success, 'runpf_vsc_mtdc solvedcase can be re-solved');

%%-----  3-terminal VSC-MTDC case  -----
mpc3 = loadcase('case5_vsc_mtdc_3term');
active3 = find(mpc3.vsc(:, c.VSC_STATUS) > 0);
[r3, success] = runpf_vsc_mtdc(mpc3, mpopt_seq);
t_ok(success, '3-terminal VSC-MTDC PF success');
t_ok(r3.iterations > 0 && r3.iterations <= 20, '3-terminal iteration count');
t_is(r3.vsc(active3, c.PAC) + r3.vsc(active3, c.PDC) + r3.vsc(active3, c.PLOSS), ...
    zeros(length(active3), 1), 6, '3-terminal VSC power balance');
t_is(r3.busdc(:, bdc.VDC), [1; 1.00482815597738; 1.00451086157824], 8, ...
    '3-terminal DC voltages');
t_ok(r3.vsc(1, c.PDC) < 0, '3-terminal slack absorbs DC power');
t_is(sum(r3.vsc(active3, c.PDC)), ...
    sum(r3.branchdc(:, brdc.PFDC) + r3.branchdc(:, brdc.PTDC)), 8, ...
    '3-terminal DC injections equal DC branch losses');
t_ok(abs(r3.vsc(1, c.PDC) - mpc3.vsc(1, c.PDC_SET)) > 1, ...
    '3-terminal slack Pdc is calculated result');
t_is(r3.vsc(2:3, c.PDC), [35; 20], 10, '3-terminal Pdc controls hold set points');
t_is(r3.vsc(1, c.VAC_PCC), mpc3.vsc(1, c.VAC_SET), 8, ...
    'VSC AC voltage control holds PCC voltage');
t_is(r3.vsc(2:3, c.QAC), [0; 0], 8, 'VSC fixed Q controls hold set points');
t_is(size(r3.ac.bus, 1), size(mpc3.bus, 1) + 2 * length(active3), 12, ...
    '3-terminal auxiliary AC buses');
t_is(r3.vsc(4, [c.PAC c.QAC c.PDC c.PLOSS c.FILTER_BUS c.INTERNAL_BUS]), ...
    zeros(1, 6), 12, '3-terminal out-of-service VSC ignored');
[r3u, success] = runpf_vsc_mtdc(mpc3, mpopt_u);
t_ok(success, '3-terminal unified VSC-MTDC PF success');
t_is(r3u.vsc(active3, [c.PAC c.QAC c.PDC c.VDC c.VAC_PCC c.VAC_INTERNAL c.PLOSS]), ...
    r3.vsc(active3, [c.PAC c.QAC c.PDC c.VDC c.VAC_PCC c.VAC_INTERNAL c.PLOSS]), ...
    6, '3-terminal unified VSC results match sequential solution');
t_is(r3u.vsc(4, [c.PAC c.QAC c.PDC c.PLOSS c.FILTER_BUS c.INTERNAL_BUS]), ...
    zeros(1, 6), 12, '3-terminal unified out-of-service VSC ignored');

%%-----  Beerten 5-bus paper validation case  -----
mpcb = loadcase('case5_vsc_mtdc_beerten');
[rb, success] = runpf_vsc_mtdc(mpcb, mpopt_seq);
t_ok(success, 'Beerten 5-bus VSC-MTDC PF success');
t_ok(rb.iterations > 0 && rb.iterations <= 20, 'Beerten iteration count');

paper_bus = [
    1   1.060    0.00;
    2   1.000   -2.39;
    3   1.000   -3.90;
    4   0.996   -4.27;
    5   0.991   -4.15;
];
got_bus = zeros(size(paper_bus, 1), 2);
for kk = 1:size(paper_bus, 1)
    row = find(rb.ac.bus(:, BUS_I) == paper_bus(kk, 1), 1);
    got_bus(kk, :) = rb.ac.bus(row, [VM VA]);
end
t_ok(max(abs(got_bus(:, 1) - paper_bus(:, 2))) < 1e-3, ...
    'Beerten AC voltage magnitudes match published table');
t_ok(max(abs(got_bus(:, 2) - paper_bus(:, 3))) < 1e-2, ...
    'Beerten AC voltage angles match published table');

paper_vsc = [
    2   0.984   -3.760   -60.00   -40.00   0.05   2.08   1.36   -58.59   1.008;
    3   1.003   -3.431    20.68     7.17   0.00   0.19   1.15    21.84   1.000;
    5   0.993   -3.340    35.00     5.00   0.01   0.51   1.19    36.21   0.998;
];
got_uc = rb.vsc(:, c.VAC_INTERNAL);
got_delta_c = zeros(size(rb.vsc, 1), 1);
got_reactor_q = zeros(size(rb.vsc, 1), 1);
for kk = 1:size(rb.vsc, 1)
    row = find(rb.ac.bus(:, BUS_I) == rb.vsc(kk, c.INTERNAL_BUS), 1);
    got_delta_c(kk) = rb.ac.bus(row, VA);
    br = rb.vsc(kk, c.REACTOR_BRANCH);
    got_reactor_q(kk) = rb.ac.branch(br, QF) + rb.ac.branch(br, QT);
end
t_ok(max(abs(got_uc - paper_vsc(:, 2))) < 2e-3, ...
    'Beerten converter internal voltages match published table');
t_ok(max(abs(got_delta_c - paper_vsc(:, 3))) < 2e-2, ...
    'Beerten converter internal angles match published table');
t_ok(max(abs(rb.vsc(:, c.PAC) - paper_vsc(:, 4))) < 0.1, ...
    'Beerten converter active powers match published table');
t_ok(max(abs(rb.vsc(:, c.QAC) - paper_vsc(:, 5))) < 0.5, ...
    'Beerten converter reactive powers match published table');
t_ok(max(abs(rb.vsc(:, c.PREACTOR_LOSS) - paper_vsc(:, 6))) < 0.01, ...
    'Beerten station active losses match published table');
t_ok(max(abs(got_reactor_q - paper_vsc(:, 7))) < 0.08, ...
    'Beerten reactor reactive losses match published table');
t_ok(max(abs(rb.vsc(:, c.PLOSS) - paper_vsc(:, 8))) < 0.05, ...
    'Beerten converter losses match published table');
t_ok(max(abs(-rb.vsc(:, c.PDC) - paper_vsc(:, 9))) < 0.1, ...
    'Beerten DC powers match published table sign convention');
t_ok(max(abs(rb.vsc(:, c.VDC) - paper_vsc(:, 10))) < 1e-3, ...
    'Beerten DC voltages match published table');
t_is(rb.vsc(:, c.PAC) + rb.vsc(:, c.PDC) + rb.vsc(:, c.PLOSS), ...
    zeros(size(rb.vsc, 1), 1), 6, 'Beerten VSC power balance');

[ru, success] = runpf_vsc_mtdc(mpcb, mpopt_u);
t_ok(success, 'Beerten unified VSC-MTDC PF success');
t_ok(ru.iterations > 0 && ru.iterations <= 10, 'Beerten unified iteration count');
t_str_match(ru.convergence.jacobian, 'analytic', ...
    'unified VSC-MTDC PF uses analytic Jacobian');
rdef = runpf_vsc_mtdc(mpcb, mpopt);
t_str_match(rdef.convergence.method, 'unified', ...
    'runpf_vsc_mtdc defaults to unified method');
t_is(ru.vsc(:, [c.PAC c.QAC c.PDC c.VDC c.VAC_PCC c.VAC_INTERNAL c.PLOSS]), ...
    rb.vsc(:, [c.PAC c.QAC c.PDC c.VDC c.VAC_PCC c.VAC_INTERNAL c.PLOSS]), ...
    6, 'Beerten unified VSC results match sequential solution');
t_is(ru.ac.bus(1:size(mpcb.bus, 1), [VM VA]), ...
    rb.ac.bus(1:size(mpcb.bus, 1), [VM VA]), ...
    6, 'Beerten unified AC voltages match sequential solution');
[rpsse_pf_u, success] = runpf_psse(mpcb, mpopt_u);
t_ok(success, 'runpf_psse delegates unified VSC-MTDC PF successfully');
t_str_match(rpsse_pf_u.psse.pf.task_class, 'unified_vsc_mtdc', ...
    'runpf_psse reports unified VSC-MTDC PF task class');
t_str_match(rpsse_pf_u.convergence.jacobian, 'analytic', ...
    'runpf_psse unified VSC-MTDC PF uses analytic Jacobian');
t_ok(rpsse_pf_u.convergence.psse_aware, ...
    'runpf_psse unified VSC-MTDC PF is PSS/E-aware');
t_ok(~isempty(strfind(rpsse_pf_u.psse.pf.formulation, 'PSS/E-aware unified')), ...
    'runpf_psse reports PSS/E-aware unified formulation');

%%-----  TESIS-style capability helpers and post-solve audit  -----
[sat_g, Pg, Qg] = gen_capability_curve(35, 10, 100, 'thermal');
t_is([sat_g Pg Qg], [0 35 10], 12, ...
    'thermal generator capability leaves interior point unchanged');
[sat_g, Pg, Qg] = gen_capability_curve(40, 10, 100, 'hydraulic');
t_is([sat_g Pg Qg], [0 40 10], 12, ...
    'hydraulic generator capability leaves interior point unchanged');
[sat_g, Pg, Qg] = gen_capability_curve(40, 10, 100, 'wind');
t_is([sat_g Pg Qg], [0 40 10], 12, ...
    'wind generator capability leaves interior point unchanged');
[sat_g, Pg, Qg, ~, info_g] = gen_capability_curve(40, 95, 100, 'thermal');
q0_g = (80^2 - 80^2 - 60^2) / (2 * 80 - 2 * 60);
s0_g = 80 - q0_g;
t_is([sat_g Pg Qg], [1 40 sqrt(s0_g^2 - 40^2) + q0_g], 10, ...
    'thermal generator capability saturates to expected arc point');
t_str_match(info_g.active_limit, 'overexcited_arc', ...
    'generator capability audits active limit');
t_is([info_g.element_base_mva info_g.P_original_pu ...
    info_g.Q_original_pu info_g.Smax_pu], [100 0.4 0.95 1], 12, ...
    'generator capability uses own MVA base');

[sat_v, Pv, Qv] = vsc_capability_geometry(0.20, 0.05, 1, 1, 0.5, 'radial');
t_is([sat_v Pv Qv], [0 0.20 0.05], 12, ...
    'VSC capability leaves interior point unchanged');
[sat_v, Pv, ~, ~, info_vp] = ...
    vsc_capability_geometry(1.30, 0.05, 1, 1, 0.5, 'radial');
t_ok(sat_v && info_vp.violated_p && abs(Pv) <= info_vp.pMax + 1e-10, ...
    'VSC capability saturates outside |P| limit');
[sat_v, Pv, Qv, ~, info_vi] = ...
    vsc_capability_geometry(0.60, -1.20, 1, 1, 0.5, 'radial');
t_is([sat_v Pv Qv], [1 0.60 / hypot(0.60, -1.20) ...
    -1.20 / hypot(0.60, -1.20)], 10, ...
    'VSC capability saturates outside AC current limit');
t_ok(info_vi.violated_current && ~info_vi.violated_p, ...
    'VSC capability audits AC current limit');
[sat_v, Pv, Qv, ~, info_vv] = ...
    vsc_capability_geometry(0.20, 0.80, 1, 1, 0.5, 'radial');
t_ok(sat_v && info_vv.violated_voltage, ...
    'VSC capability saturates outside internal-voltage limit');
t_ok(info_vv.inside_final, ...
    'VSC capability projection lands inside final feasible region');
t_is(Qv / Pv, 0.80 / 0.20, 10, ...
    'VSC radial mode preserves power factor');
[sat_v, Pp, Qp, ~, info_vq] = ...
    vsc_capability_geometry(0.20, 0.80, 1, 1, 0.5, 'preservar_p');
t_ok(sat_v && abs(Pp - 0.20) < 1e-10, ...
    'VSC preservar_p mode preserves feasible P');
t_ok(abs(Qp - info_vq.qMax) < 1e-10, ...
    'VSC preservar_p mode clips Q to feasible interval');
[~, ~, ~, ~, info_vw] = ...
    vsc_capability_curve(50, 25, 250, 1, rb.vsc(2, :), [], 1.15, rb.baseMVA);
t_is([info_vw.element_base_mva info_vw.P_original_pu ...
    info_vw.Q_original_pu info_vw.Smax_pu], [250 0.2 0.1 1], 12, ...
    'VSC capability uses own converter MVA base');
t_is(info_vw.xEq_element, info_vw.xEq_system * 250 / rb.baseMVA, 12, ...
    'VSC capability converts station reactance to own MVA base');
policy_slack = vsc_capability_policy(rb.vsc(2, :));
t_str_match(policy_slack.projection_mode, 'preservar_p', ...
    'VSC capability policy defaults DC slack to preservar_p');
t_is(policy_slack.target_ac_mode_if_saturated, c.VSC_AC_Q, 12, ...
    'VSC capability policy clips Q for DC slack voltage control');
mpcd_policy = loadcase('case5_vsc_mtdc_beerten_droop');
policy_droop = vsc_capability_policy(mpcd_policy.vsc(2, :));
t_str_match(policy_droop.projection_mode, 'preservar_p', ...
    'VSC capability policy defaults DC droop to preservar_p');
mpca_policy = loadcase('case5_vsc_mtdc_beerten_all_controls');
policy_pdc = vsc_capability_policy(mpca_policy.vsc(3, :));
t_str_match(policy_pdc.projection_mode, 'radial', ...
    'VSC capability policy defaults fixed-PDC converters to radial');
policy_pdc_override = vsc_capability_policy(mpca_policy.vsc(3, :), ...
    struct('mode', 'preservar_p'), 3, 3);
t_str_match(policy_pdc_override.reason, 'configured', ...
    'VSC capability policy reports configured projection overrides');
t_str_match(policy_pdc_override.projection_mode, 'preservar_p', ...
    'VSC capability policy lets fixed-PDC converters use configured mode');
mpc_meta = rb;
mpc_meta.vsc([1 2], c.PAC) = 60;
mpc_meta.vsc([1 2], c.QAC) = 50;
mpc_meta.vsc([1 2], c.VAC_INTERNAL) = 1;
mpc_meta.vsc_capability = struct('Snom', [70 160 150], ...
    'VconvMax', [1.15 1.15 1.15]);
cap_meta = check_vsc_capability(mpc_meta, struct('vsc_smax', 300));
t_is([cap_meta.elements(1:2).Smax], [70 160], 12, ...
    'VSC capability metadata overrides global Smax option');
t_is([cap_meta.elements(1:2).sat], [1 0], 12, ...
    'VSC capability metadata gives per-converter curves');
t_str_match(cap_meta.elements(1).Smax_source, 'metadata', ...
    'VSC capability audit reports metadata Smax source');
t_is(cap_meta.elements(1).info.xEq_element, ...
    cap_meta.elements(1).info.xEq_system * 70 / rb.baseMVA, 12, ...
    'VSC capability metadata converts station reactance to own MVA base');
mpc_vec = rmfield(mpc_meta, 'vsc_capability');
cap_vec = check_vsc_capability(mpc_vec, ...
    struct('vsc_smax', [70 160 150]));
t_is([cap_vec.elements(1:2).Smax], [70 160], 12, ...
    'VSC capability supports deterministic vector Smax options');
mpc_vmax = rb;
mpc_vmax.vsc_capability = struct('Snom', [250 250 250], ...
    'VconvMax', [1.05 1.30 1.15]);
cap_vmax = check_vsc_capability(mpc_vmax);
t_ok(cap_vmax.elements(1).info.qMax < cap_vmax.elements(2).info.qMax && ...
    strcmp(cap_vmax.elements(1).Vmax_source, 'metadata'), ...
    'VSC capability metadata VconvMax changes the converter Q range');

t_vsc_expect_error(@() vsc_capability_geometry(0, 0, 0, 1, 0.5), ...
    'Smax', 'VSC capability rejects non-positive Smax');
t_vsc_expect_error(@() vsc_capability_geometry(0, 0, 1, 0, 0.5), ...
    'V', 'VSC capability rejects non-positive voltage');
t_vsc_expect_error(@() check_vsc_capability(rb, struct('vsc_idx', 99)), ...
    'VSC index', 'VSC capability audit rejects invalid index');
t_vsc_expect_error(@() vsc_capability_geometry(0, 0, 1, 1, 0.5, 'radial', 0), ...
    'Vmax', 'VSC capability rejects invalid Vmax');
mpc_bad_meta_len = rb;
mpc_bad_meta_len.vsc_capability = struct('Snom', [250 250]);
t_vsc_expect_error(@() check_vsc_capability(mpc_bad_meta_len), ...
    'Snom has invalid length', 'VSC capability rejects malformed metadata length');
t_vsc_expect_error(@() check_vsc_capability(rb, struct('vsc_smax', [250 250])), ...
    'vsc_smax has invalid length', 'VSC capability rejects invalid option length');

cap_pf = check_capability_limits(rb);
t_is([cap_pf.count cap_pf.gen.count cap_pf.vsc.count cap_pf.violations], ...
    [5 2 3 0], 12, 'Beerten PF capability audit covers gen and VSC rows');
t_ok(isfield(cap_pf.vsc.elements, 'P_saturated') && ...
    isfield(cap_pf.gen.elements, 'active_limit'), ...
    'Beerten PF capability audit reports saturated points and limits');
t_str_match(cap_pf.gen.elements(1).active_limit, 'slack_exempt', ...
    'Beerten PF capability audit exempts slack generator');

mpcps_pf = vsc_psse_swshunt_case(mpcb);
[rpsse_sw_pf, success] = runpf_psse(mpcps_pf, mpopt_u);
t_ok(success, 'runpf_psse unified VSC-MTDC PF settles PSS/E switched shunt');
