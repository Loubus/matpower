function chk = vsc_unified_jacobian_check(mpc, mpopt)
ctx = vsc_unified_setup(mpc, mpopt);
x = ctx.x0;
[~, eval] = vsc_unified_mismatch(ctx, x, []);
J = vsc_unified_jacobian(ctx, eval);
Jfd = zeros(size(J));
for jj = 1:length(x)
    h = 1e-6 * max(1, abs(x(jj)));
    xp = x;
    xm = x;
    xp(jj) = xp(jj) + h;
    xm(jj) = xm(jj) - h;
    Fp = vsc_unified_mismatch(ctx, xp, []);
    Fm = vsc_unified_mismatch(ctx, xm, []);
    Jfd(:, jj) = (Fp - Fm) / (2 * h);
end
err = abs(J - Jfd);
rel = err ./ max(1, abs(Jfd));

nva = length(ctx.model.nonref);
nvm = length(ctx.model.vm_vars);
npac = length(ctx.model.pac_vars);
ndc = length(ctx.model.dc_var);
col_ac = [1:nva nva + (1:nvm)];
col_pac = nva + nvm + (1:npac);
col_vdc = nva + nvm + npac + (1:ndc);

row_p = 1:length(ctx.model.nonref);
row_q = length(row_p) + (1:length(ctx.model.qeq));
row_v = length(row_p) + length(row_q) + (1:length(ctx.model.vctrl));
row_bal = length(row_p) + length(row_q) + length(row_v) + ...
    (1:length(ctx.model.pac_vars));
row_dc = length(row_p) + length(row_q) + length(row_v) + ...
    length(row_bal) + (1:length(ctx.model.dc_var));
row_vsc_dc = [row_v row_bal row_dc];

chk = struct( ...
    'max_abs',        vsc_max_abs(err), ...
    'max_rel',        vsc_max_abs(rel), ...
    'ac_cols_abs',    vsc_max_abs(err(:, col_ac)), ...
    'pac_cols_abs',   vsc_max_abs(err(:, col_pac)), ...
    'vdc_cols_abs',   vsc_max_abs(err(:, col_vdc)), ...
    'vsc_dc_rows_abs', vsc_max_abs(err(row_vsc_dc, :)) );

function chk = vsc_unified_cpf_jacobian_check(mpcb, mpct, mpopt)
args = struct('base', mpcb, 'target', mpct, 'mpopt', mpopt, ...
    'lam', 0.15, 'parameterization', 3);
sys0 = vsc_cpf_internal_system(args);
nx = length(sys0.x);
z = (1:(nx + 1))';
z = z / norm(z);
h = 0.03;
x = sys0.x;
lam = args.lam;
args.x = x;
args.z = z;
args.h = h;
args.xprev = x - h * z(1:nx);
args.lamprev = lam - h * z(end);
sys = vsc_cpf_internal_system(args);

Afd = zeros(size(sys.A));
zeta = [x; lam];
for jj = 1:(nx + 1)
    step = 1e-6 * max(1, abs(zeta(jj)));
    xp = x;
    xm = x;
    lamp = lam;
    lamm = lam;
    if jj <= nx
        xp(jj) = xp(jj) + step;
        xm(jj) = xm(jj) - step;
    else
        lamp = lamp + step;
        lamm = lamm - step;
    end
    Fp = vsc_cpf_augmented_mismatch(sys.ctx, sys.Sdelta, xp, lamp, ...
        z, h, args.xprev, args.lamprev);
    Fm = vsc_cpf_augmented_mismatch(sys.ctx, sys.Sdelta, xm, lamm, ...
        z, h, args.xprev, args.lamprev);
    Afd(:, jj) = (Fp - Fm) / (2 * step);
end
err = abs(sys.A - Afd);
chk = struct( ...
    'aug_abs',     vsc_max_abs(err), ...
    'block_j_abs', vsc_max_abs(err(1:nx, 1:nx)), ...
    'dlam_abs',    vsc_max_abs(err(1:nx, end)), ...
    'param_abs',   vsc_max_abs(err(end, :)) );

function F = vsc_cpf_augmented_mismatch(ctx, Sdelta, x, lam, z, h, ...
        xprev, lamprev)
ctx_lam = vsc_cpf_test_context_at_lambda(ctx, lam);
[F0, ~] = vsc_unified_mismatch(ctx_lam, x, ctx.Sbase + lam * Sdelta);
P = z' * ([x; lam] - [xprev; lamprev]) - h;
F = [F0; P];

function ctx_lam = vsc_cpf_test_context_at_lambda(ctx, lam)
ctx_lam = ctx;
if ~isfield(ctx, 'cpf_transfer')
    return;
end
tr = ctx.cpf_transfer;
c = idx_vsc;
bdc = idx_busdc;
cols = [c.PAC_SET c.QAC_SET c.VAC_SET c.PDC_SET c.VDC_SET c.KDROOP];
mpc = tr.base;
mpc.vsc(:, cols) = tr.base.vsc(:, cols) + ...
    lam * (tr.target.vsc(:, cols) - tr.base.vsc(:, cols));
mpc.busdc(:, bdc.VDC) = tr.base.busdc(:, bdc.VDC) + ...
    lam * (tr.target.busdc(:, bdc.VDC) - tr.base.busdc(:, bdc.VDC));
ctx_lam.mpc = mpc;

function m = vsc_max_abs(x)
if isempty(x)
    m = 0;
else
    m = max(abs(x(:)));
end
