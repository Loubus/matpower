function report = check_vsc_capability(results, opt)
% check_vsc_capability - Audits VSC P-Q capability after PF/CPF.
% ::
%
%   REPORT = CHECK_VSC_CAPABILITY(RESULTS)
%   REPORT = CHECK_VSC_CAPABILITY(RESULTS, OPT)
%
%   Evaluates each selected in-service VSC against the TESIS-inspired
%   geometric capability region without modifying RESULTS. This is a
%   post-solve saturation audit, not OPF constraint enforcement. DC slack and
%   droop converters default to MODE = 'preservar_p'; other VSCs default to
%   MODE = 'radial'.
%
%   Optional OPT fields:
%       VSC_IDX   selected VSC rows, default all in-service converters
%       MODE      scalar/cell mode override
%       VMAX      scalar/vector internal-voltage limit, default 1.15
%       VSC_SMAX  scalar/vector Smax override, default min station RATE_A
%
% See also vsc_capability_curve, check_capability_limits,
% enforce_vsc_capability_active_set.

%   MATPOWER
%   Copyright (c) 2026, Power Systems Engineering Research Center (PSERC)
%
%   This file is part of MATPOWER.
%   Covered by the 3-clause BSD License (see LICENSE file for details).
%   See https://matpower.org for more info.

if nargin < 2 || isempty(opt)
    opt = struct();
end
mpc = loadcase(results);
c = idx_vsc;
elements = repmat(empty_element(), 0, 1);

if ~isfield(mpc, 'vsc') || isempty(mpc.vsc)
    report = build_report(elements);
    return;
end

idx = selected_vsc(mpc, opt, c);
elements = repmat(empty_element(), length(idx), 1);
for kk = 1:length(idx)
    k = idx(kk);
    P0 = vsc_col(mpc.vsc, k, c.PAC, c.PAC_SET);
    Q0 = vsc_col(mpc.vsc, k, c.QAC, c.QAC_SET);
    V = vsc_voltage(mpc.vsc, k, c);
    params = vsc_capability_params(mpc, opt, k, kk);
    [sat, Psat, Qsat, Ssat, info] = vsc_capability_curve( ...
        P0, Q0, params.Smax, V, mpc.vsc(k, :), ...
        params.mode, params.Vmax, mpc.baseMVA);
    elements(kk) = struct( ...
        'type',          'vsc', ...
        'idx',           k, ...
        'bus',           mpc.vsc(k, c.VSC_BUS), ...
        'dc_bus',        mpc.vsc(k, c.BUSDC), ...
        'status',        mpc.vsc(k, c.VSC_STATUS), ...
        'ac_mode',       mpc.vsc(k, c.AC_MODE), ...
        'dc_mode',       mpc.vsc(k, c.DC_MODE), ...
        'V',             V, ...
        'Smax',          info.Smax, ...
        'P',             P0, ...
        'Q',             Q0, ...
        'S',             abs(P0 + 1j * Q0), ...
        'P_saturated',   Psat, ...
        'Q_saturated',   Qsat, ...
        'S_saturated',   Ssat, ...
        'sat',           sat, ...
        'active_limit',  info.active_limit, ...
        'margin',        info.margin, ...
        'mode',          info.mode, ...
        'policy_reason', info.policy_reason, ...
        'target_ac_mode_if_saturated', ...
                         info.target_ac_mode_if_saturated, ...
        'Smax_source',   params.Smax_source, ...
        'Vmax_source',   params.Vmax_source, ...
        'mode_source',   params.mode_source, ...
        'info',          info );
end
report = build_report(elements);


function idx = selected_vsc(mpc, opt, c)
nv = size(mpc.vsc, 1);
if isfield(opt, 'vsc_idx') && ~isempty(opt.vsc_idx)
    idx = opt.vsc_idx(:);
    if ~isnumeric(idx) || any(~isfinite(idx)) || any(idx < 1) || ...
            any(idx > nv) || any(idx ~= fix(idx))
        error('check_vsc_capability: VSC index is invalid');
    end
else
    idx = find(mpc.vsc(:, c.VSC_STATUS) > 0);
end


function val = vsc_col(vsc, row, result_col, set_col)
if size(vsc, 2) >= result_col && isfinite(vsc(row, result_col))
    val = vsc(row, result_col);
else
    val = vsc(row, set_col);
end


function V = vsc_voltage(vsc, row, c)
if size(vsc, 2) >= c.VAC_PCC && isfinite(vsc(row, c.VAC_PCC)) && ...
        vsc(row, c.VAC_PCC) > 0
    V = vsc(row, c.VAC_PCC);
elseif size(vsc, 2) >= c.VAC_INTERNAL && ...
        isfinite(vsc(row, c.VAC_INTERNAL)) && ...
        vsc(row, c.VAC_INTERNAL) > 0
    V = vsc(row, c.VAC_INTERNAL);
else
    V = vsc(row, c.VAC_SET);
end


function report = build_report(elements)
sat = zeros(length(elements), 1);
for kk = 1:length(elements)
    sat(kk) = elements(kk).sat;
end
report = struct( ...
    'type',        'vsc', ...
    'count',       length(elements), ...
    'violations',  sum(sat), ...
    'elements',    elements );


function e = empty_element()
e = struct( ...
    'type',          '', ...
    'idx',           [], ...
    'bus',           [], ...
    'dc_bus',        [], ...
    'status',        [], ...
    'ac_mode',       [], ...
    'dc_mode',       [], ...
    'V',             [], ...
    'Smax',          [], ...
    'P',             [], ...
    'Q',             [], ...
    'S',             [], ...
    'P_saturated',   [], ...
    'Q_saturated',   [], ...
    'S_saturated',   [], ...
    'sat',           [], ...
    'active_limit',  '', ...
    'margin',        [], ...
    'mode',          '', ...
    'policy_reason', '', ...
    'target_ac_mode_if_saturated', [], ...
    'Smax_source',   '', ...
    'Vmax_source',   '', ...
    'mode_source',   '', ...
    'info',          struct() );
